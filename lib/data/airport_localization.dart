bool _containsChinese(String value) =>
    RegExp(r'[\u3400-\u9fff]').hasMatch(value);

String localizedAirportCity(Airport airport) {
  final code = airport.iataCode.trim().toUpperCase();
  final mapped = _airportCityNames[code];
  if (mapped != null) return mapped;
  final raw = airport.city.trim();
  if (_containsChinese(raw)) return raw;
  // OurAirports carries a small set of Chinese keywords even when the
  // English city field is unchanged. Use the compact Chinese keyword as a
  // useful map label rather than falling back to an empty marker label.
  final sourceChinese = _sourceChineseAirportName(airport);
  if (sourceChinese.isNotEmpty) {
    final compact = _compactAirportName(sourceChinese, '');
    if (compact.isNotEmpty) return compact;
  }
  return '';
}

String localizedAirportLabel(Airport airport) {
  final city = localizedAirportCity(airport);
  final terminal = _airportTerminals[airport.iataCode.trim().toUpperCase()];
  final suffix = terminal ?? '';
  if (city.isEmpty) return suffix.isEmpty ? '机场' : '机场$suffix';
  return '$city机场$suffix';
}

/// The compact airport name used in flight cards and the add-flight form.
///
/// Keep this presentation value identical anywhere an airport is shown next
/// to its IATA code: city + airport + terminal when we know it (for example,
/// `深圳机场T3`). If a city is not in the curated map, use a Chinese source
/// alias when OurAirports provides one, then preserve the source's real
/// English name instead of showing a generic placeholder.
String localizedAirportDisplayName(Airport airport) {
  final code = airport.iataCode.trim().toUpperCase();
  final compact = localizedAirportLabel(airport);
  if (compact != '机场' && !compact.startsWith('机场T')) return compact;

  final sourceChinese = _sourceChineseAirportName(airport);
  if (sourceChinese.isNotEmpty) return sourceChinese;

  final mapped = _airportNames[code];
  if (mapped != null) return mapped;

  final sourceName = airport.name.trim();
  if (_containsChinese(sourceName)) return sourceName;
  // Keep the source's real English name when a Chinese alias is unavailable.
  // A generic “机场” label loses the only useful identity in the picker.
  if (sourceName.isNotEmpty) return sourceName;
  return code.isEmpty ? '机场' : '机场（$code）';
}

/// The unambiguous airport name used by flight records.
///
/// A record card must distinguish airports that share one city (for example,
/// Beijing Capital vs. Beijing Daxing). Use the curated/source Chinese name
/// first, then the source's English name when no Chinese alias exists. Append
/// a known terminal without replacing the airport name with the shorter
/// city-only label.
String localizedAirportCardName(Airport airport) {
  final code = airport.iataCode.trim().toUpperCase();
  final sourceName = _sourceChineseAirportName(airport);
  final city = localizedAirportCity(airport);
  final fullName =
      _airportNames[code] ??
      (sourceName.isNotEmpty
          ? sourceName
          : (airport.name.trim().isNotEmpty
                ? airport.name.trim()
                : (city.isNotEmpty ? '$city机场' : '机场')));
  final name = _compactAirportName(fullName, city);
  final terminal = _airportTerminals[code];
  if (name.isEmpty) {
    return terminal == null ? '机场' : '机场$terminal';
  }
  if (terminal == null || name.contains(terminal)) return name;
  return '$name$terminal';
}

/// A two-line airport name for the compact flight record card.
///
/// The stored/card name remains the complete compact Chinese name so imports
/// and edit screens keep their existing values. The route card is a summary,
/// however, so long foreign airport names are split into a city line and a
/// short landmark line. IATA still carries the unambiguous identity.
String localizedAirportCardDisplayName(Airport airport) {
  final compact = localizedAirportCardName(airport).trim();
  final city = localizedAirportCity(airport).trim();
  if (compact.isEmpty || city.isEmpty || !compact.startsWith(city)) {
    return compact;
  }

  // The route card has a compact two-column slot. Short Chinese labels fit
  // comfortably on one line; only labels beyond that capacity use the
  // semantic city / landmark two-line treatment below.
  if (compact.runes.length <= 6) return compact;

  var landmark = compact.substring(city.length).trim();
  final terminalMatch = RegExp(r'(T\d+[A-Z]?)$').firstMatch(landmark);
  final terminal = terminalMatch?.group(1);
  if (terminal != null) {
    landmark = landmark.substring(0, terminalMatch!.start).trim();
  }
  landmark = _compactAirportLandmark(landmark);

  if (landmark.isEmpty) {
    return terminal == null ? city : '$city\n$terminal';
  }
  return terminal == null ? '$city\n$landmark' : '$city\n$landmark $terminal';
}

String _compactAirportLandmark(String value) {
  final normalized = value.replaceAll(RegExp(r'^[·•・,，、\s]+'), '').trim();
  if (normalized.isEmpty || normalized.runes.length <= 7) {
    return normalized;
  }

  // Long transliterated names are easier to scan by keeping the final
  // landmark token (for example, “奥利弗·雷金纳德·坦博” → “坦博”).
  final parts = normalized
      .split(RegExp(r'[·•・,，、/／\-—–]+'))
      .map((part) => part.trim())
      .where((part) => part.isNotEmpty)
      .toList(growable: false);
  return parts.length > 1 ? parts.last : normalized;
}

String _compactAirportName(String value, String city) {
  var name = value
      .replaceAll(RegExp(r'\s*[（(][^）)]*[）)]'), '')
      .replaceAll(RegExp(r'\s*[，,;；|].*$'), '')
      .trim();
  if (name.isEmpty) return name;

  // “深圳宝安国际机场” becomes “深圳宝安”. The city-only form
  // “香港国际机场” keeps “国际” to remain distinguishable and readable;
  // other names drop the whole “国际机场” suffix.
  if (name.endsWith('国际机场')) {
    final withoutAirport = name.substring(0, name.length - 2);
    // Hong Kong's official short form is conventionally written “香港国际”;
    // for other airports always remove “国际机场”, even when a source keyword
    // made the city fallback include the airport's local landmark.
    final cityOnlyInternational =
        name == '香港国际机场' && city.isNotEmpty && withoutAirport == '$city国际';
    name = cityOnlyInternational
        ? withoutAirport
        : name.substring(0, name.length - 4);
  } else if (name.endsWith('机场')) {
    name = name.substring(0, name.length - 2);
  }
  return name.trim();
}

/// A localized airport name for picker subtitles. Curated Chinese names and
/// Chinese source keywords take priority; when neither is available, keep the
/// source's real English airport name instead of replacing it with a generic
/// “机场” label.
String localizedAirportName(Airport airport) {
  final code = airport.iataCode.trim().toUpperCase();
  final mapped = _airportNames[code];
  if (mapped != null) return mapped;
  final sourceChinese = _sourceChineseAirportName(airport);
  if (sourceChinese.isNotEmpty) return sourceChinese;
  final sourceName = airport.name.trim();
  if (sourceName.isNotEmpty) {
    return code.isEmpty ? sourceName : '$sourceName（$code）';
  }
  final city = localizedAirportCity(airport);
  if (city.isNotEmpty) return '$city机场（$code）';
  return code.isEmpty ? '机场' : '机场（$code）';
}

/// Returns local names that commonly appear in Chinese itinerary exports.
///
/// Keep this API presentation-agnostic so the same aliases can be used by
/// airport search and spreadsheet import while the visible airport name stays
/// consistent with [localizedAirportName].
List<String> localizedAirportSearchAliases(Airport airport) {
  final code = airport.iataCode.trim().toUpperCase();
  return _airportSearchAliases[code] ?? const [];
}

String _sourceChineseAirportName(Airport airport) {
  for (final keyword in airport.keywords) {
    final value = keyword
        .split(RegExp(r'[，,;；|]'))
        .map((part) => part.trim())
        .firstWhere(
          (part) => part.isNotEmpty && _containsChinese(part),
          orElse: () => '',
        );
    if (!_containsChinese(value)) continue;
    if (value.contains('机场') || value.contains('機場')) return value;
  }
  return '';
}

/// Converts an ISO 3166-1 alpha-2 country code into its native flag emoji.
/// Unknown or malformed codes use a neutral globe so ranking rows stay clear.
String localizedCountryFlag(String? countryCode) {
  final code = countryCode?.trim().toUpperCase() ?? '';
  if (code.length != 2 ||
      code.codeUnits.any((unit) => unit < 65 || unit > 90)) {
    return '🌐';
  }
  return String.fromCharCodes(
    code.codeUnits.map((unit) => 0x1F1E6 + unit - 65),
  );
}

